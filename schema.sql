-- Messages reference tickets by title so this block is id-agnostic.
INSERT INTO ticket_messages (ticket_id, message_text, author)
SELECT ticket_id, m.message_text, m.author
FROM tickets t
JOIN (VALUES
    ('Cannot log into portal',       'I get "invalid credentials" even after a reset.', 'alice@example.com'),
    ('Cannot log into portal',       'Thanks for reporting — can you confirm your username?', 'support@example.com'),
    ('Report export is missing rows','The CSV export drops the last 200 rows.',          'bob@example.com'),
    ('Report export is missing rows','Reproduced it. Looks like a pagination bug.',       'support@example.com'),
    ('Report export is missing rows','Fix is in progress, ETA end of week.',              'support@example.com'),
    ('Request: add dark mode',       'Would love a dark theme for late-night work.',      'carol@example.com'),
    ('Request: add dark mode',       'Shipped in v2.3 — closing this out.',               'support@example.com')
) AS m(title, message_text, author)
  ON t.title = m.title;

-- ---------------------------------------------------------------------
-- 4. Quick verification
-- ---------------------------------------------------------------------
SELECT t.ticket_id, t.title, t.status, t.priority,
       COUNT(msg.message_id) AS message_count
FROM tickets t
LEFT JOIN ticket_messages msg ON msg.ticket_id = t.ticket_id
GROUP BY t.ticket_id, t.title, t.status, t.priority
ORDER BY t.ticket_id;
