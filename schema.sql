-- BEFORE RUNNING: replace every <DATABRICKS_CLIENT_ID> below with your
-- app's service-principal client id (the DATABRICKS_CLIENT_ID from the
-- app's Environment tab). It looks like: 6b215d2b-f099-4bdb-900a-60837201ecec
