-- ---------------------------------------------------------------------
-- 0. OAuth auth for the app's service principal (run once per project)
-- ---------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS databricks_auth;

-- Create a Postgres role tied to the app's service principal.
-- Safe to skip/ignore an error if the role already exists.
SELECT databricks_create_role('<DATABRICKS_CLIENT_ID>', 'service_principal');

GRANT CONNECT ON DATABASE databricks_postgres TO "<DATABRICKS_CLIENT_ID>";
GRANT USAGE ON SCHEMA public TO "<DATABRICKS_CLIENT_ID>";

-- ---------------------------------------------------------------------
-- 1. Tables
-- ---------------------------------------------------------------------
DROP TABLE IF EXISTS ticket_messages;
DROP TABLE IF EXISTS tickets;

CREATE TABLE tickets (
    ticket_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       TEXT        NOT NULL,
    status      TEXT        NOT NULL DEFAULT 'open'
                            CHECK (status IN ('open', 'in_progress', 'resolved')),
    created_by  TEXT        NOT NULL,
    created_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- bonus columns (priority + category)
    priority    TEXT        NOT NULL DEFAULT 'medium'
                            CHECK (priority IN ('low', 'medium', 'high')),
    category    TEXT        NOT NULL DEFAULT 'general'
);

CREATE TABLE ticket_messages (
    message_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id     BIGINT    NOT NULL
                            REFERENCES tickets(ticket_id) ON DELETE CASCADE,
    message_text  TEXT      NOT NULL,
    author        TEXT      NOT NULL,
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ticket_messages_ticket_id ON ticket_messages(ticket_id);

-- ---------------------------------------------------------------------
-- 2. Table permissions for the service principal
--    (service principals do NOT inherit default schema permissions)
-- ---------------------------------------------------------------------
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE tickets         TO "<DATABRICKS_CLIENT_ID>";
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE ticket_messages TO "<DATABRICKS_CLIENT_ID>";

-- ---------------------------------------------------------------------
-- 3. Sample data
--    3 tickets, >=2 messages each, 2+ distinct statuses
-- ---------------------------------------------------------------------
INSERT INTO tickets (title, status, created_by, priority, category) VALUES
    ('Cannot log into portal',        'open',        'alice@example.com', 'high',   'access'),
    ('Report export is missing rows',  'in_progress', 'bob@example.com',   'medium', 'reporting'),
